// Generates theme/variables.css from theme/pencil-variables.json, the snapshot of data/orchester2.pen's variables
// (server.md, "The web workspace"). `npm run tokens` writes it; `tests/tokens.test.ts` fails when the two differ.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SNAPSHOT = fileURLToPath(new URL("../theme/pencil-variables.json", import.meta.url));
const OUTPUT = fileURLToPath(new URL("../theme/variables.css", import.meta.url));

// The Pencil prefix of each number variable and the CSS prefix it becomes.
const NUMBER_PREFIXES: readonly [string, string][] = [
  ["spacing_", "space-"],
  ["radius_", "radius-"],
  ["border_size_", "border-"],
  ["control_height_", "control-"],
];

const FONT_FALLBACKS: Readonly<Record<string, string>> = { font_sans: "system-ui, sans-serif", font_mono: "ui-monospace, monospace" };

interface Variable {
  readonly type: "color" | "number" | "string";
  readonly value: unknown;
}

export interface Snapshot {
  readonly source: string;
  readonly variables: Readonly<Record<string, Variable>>;
}

type Mode = "dark" | "light";

function cssName(name: string): string {
  return name.replaceAll("_", "-");
}

function numberName(name: string): string {
  const prefix = NUMBER_PREFIXES.find(([pencil]) => name.startsWith(pencil));
  if (prefix === undefined) {
    throw new Error(`no CSS name for the number variable ${name}`);
  }
  return `${prefix[1]}${cssName(name.slice(prefix[0].length))}`;
}

function declarations(variables: Snapshot["variables"], mode: Mode): string[] {
  const lines: string[] = [];
  for (const [name, { type, value }] of Object.entries(variables)) {
    if (type === "color") {
      lines.push(`  --color-${cssName(name)}: ${(value as Record<Mode, string>)[mode].toLowerCase()};`);
    } else if (mode === "dark" && type === "number") {
      lines.push(`  --${numberName(name)}: ${String(value)}px;`);
    } else if (mode === "dark" && type === "string") {
      lines.push(`  --${cssName(name)}: "${String(value)}", ${FONT_FALLBACKS[name] ?? "sans-serif"};`);
    }
  }
  return lines;
}

export function generate(snapshot: Snapshot): string {
  const { variables } = snapshot;
  return [
    "/* Generated by scripts/tokens.ts from theme/pencil-variables.json (data/orchester2.pen). Do not edit. */",
    "",
    ":root {",
    "  color-scheme: dark;",
    ...declarations(variables, "dark"),
    "}",
    "",
    "@media (prefers-color-scheme: light) {",
    "  :root {",
    "    color-scheme: light;",
    ...declarations(variables, "light").map((line) => `  ${line}`),
    "  }",
    "}",
    "",
  ].join("\n");
}

export function read(): Snapshot {
  return JSON.parse(readFileSync(SNAPSHOT, "utf8")) as Snapshot;
}

export const OUTPUT_FILE = OUTPUT;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, generate(read()));
  console.log(`wrote ${OUTPUT}`);
}
